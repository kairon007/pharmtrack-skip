#!/bin/bash
set -e

# Generate User.xcconfig for iOS build
# This file allows Xcode to read variables like APPLE_TEAM_ID from the environment

IOS_CONFIG_DIR="Darwin"
IOS_CONFIG_FILE="$IOS_CONFIG_DIR/User.xcconfig"

echo "🔧 Generating iOS configuration..."

# Ensure directory exists
mkdir -p "$IOS_CONFIG_DIR"

# Load .env variables if .env exists
if [ -f .env ]; then
  export $(grep -v '^#' .env | xargs)
fi

# Write config file
echo "// Generated file - DO NOT EDIT" > "$IOS_CONFIG_FILE"
echo "// This file is generated by scripts/generate-ios-config.sh" >> "$IOS_CONFIG_FILE"
echo "" >> "$IOS_CONFIG_FILE"

if [ -n "$APPLE_TEAM_ID" ]; then
  echo "DEVELOPMENT_TEAM = $APPLE_TEAM_ID" >> "$IOS_CONFIG_FILE"
  echo "TEAM_ID = $APPLE_TEAM_ID" >> "$IOS_CONFIG_FILE"
  echo "✅ Added DEVELOPMENT_TEAM to $IOS_CONFIG_FILE"
else
  echo "// APPLE_TEAM_ID not set in .env" >> "$IOS_CONFIG_FILE"
  echo "⚠️  APPLE_TEAM_ID not found in .env. Automatic signing might fail if Team is not selected in Xcode."
fi

# Add permission validation
chmod +x scripts/generate-ios-config.sh
